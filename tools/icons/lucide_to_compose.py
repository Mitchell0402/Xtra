#!/usr/bin/env python3
"""Generates app/src/main/java/.../ui/design/icons/LucideIcons.kt from the Lucide SVGs in tools/icons/lucide.

The SVGs are lucide-static 0.460.0 (ISC licence, tools/icons/lucide/LICENSE), downloaded from
https://unpkg.com/lucide-static@0.460.0/icons/<name>.svg. To add an icon, drop its SVG into tools/icons/lucide and
rerun:  python tools/icons/lucide_to_compose.py

Every shape becomes one path string; the Kotlin side strokes them at the plan's 1.75 line width (plan section 4).
Icons listed in FILLED also get a "<Name>Filled" variant for selected states: closed shapes are filled, open strokes
stay strokes ("all" fills open paths too, for shapes like the user's shoulders).
"""
import os
import re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "lucide")
OUT = os.path.join(HERE, "..", "..", "app", "src", "main", "java", "com", "github", "andreyasadchy", "xtra", "ui",
                   "design", "icons", "LucideIcons.kt")

FILLED = {
    "heart": "closed", "layout-grid": "closed", "star": "closed", "bookmark": "closed", "bell": "closed",
    "user": "all", "house": "closed", "message-circle": "closed", "circle-dot": "closed", "play": "closed",
    "pause": "closed", "download": "closed", "folder": "closed", "shield-check": "closed",
}


def num(v):
    f = float(v)
    return str(int(f)) if f == int(f) else repr(round(f, 4))


def shape_to_path(el):
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return a["d"], a["d"].strip()[-1] in "zZ"
    if tag == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0Z", True
    if tag == "ellipse":
        cx, cy, rx, ry = (float(a[k]) for k in ("cx", "cy", "rx", "ry"))
        return f"M{num(cx - rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0Z", True
    if tag == "line":
        return f"M{num(a['x1'])} {num(a['y1'])}L{num(a['x2'])} {num(a['y2'])}", False
    if tag in ("polyline", "polygon"):
        pts = re.findall(r"-?[\d.]+", a["points"])
        pairs = [f"{num(pts[i])} {num(pts[i + 1])}" for i in range(0, len(pts), 2)]
        d = "M" + "L".join(pairs)
        return (d + "Z", True) if tag == "polygon" else (d, False)
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        if rx == 0:
            return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}Z", True
        return (f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(ry)}"
                f"v{num(h - 2 * ry)}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(ry)}h{num(-(w - 2 * rx))}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(-ry)}v{num(-(h - 2 * ry))}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(-ry)}Z"), True
    raise ValueError(f"unsupported element {tag}")


def kotlin_name(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("-"))


def main():
    icons = []
    for file in sorted(os.listdir(SRC)):
        if not file.endswith(".svg"):
            continue
        name = file[:-4]
        root = ET.parse(os.path.join(SRC, file)).getroot()
        shapes = [shape_to_path(el) for el in root.iter() if el is not root and el.tag.split("}")[-1] != "title"]
        icons.append((name, shapes))

    lines = [
        "// Generated by tools/icons/lucide_to_compose.py from Lucide (lucide-static 0.460.0, ISC licence). Do not edit.",
        "@file:Suppress(\"unused\")",
        "",
        "package com.github.andreyasadchy.xtra.ui.design.icons",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/** Lucide line icons drawn at the Lagoon stroke width; `*Filled` variants are for selected states. */",
        "object LucideIcons {",
    ]
    for name, shapes in icons:
        kn = kotlin_name(name)
        args = ", ".join(f"\"{d}\"" for d, _ in shapes)
        lines.append(f"    val {kn}: ImageVector by lazy {{ lucide(\"{kn}\", null, {args}) }}")
        if name in FILLED:
            mode = FILLED[name]
            mask = "".join("1" if (closed or mode == "all") else "0" for _, closed in shapes)
            lines.append(f"    val {kn}Filled: ImageVector by lazy {{ lucide(\"{kn}Filled\", \"{mask}\", {args}) }}")
    lines.append("}")
    lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(icons)} icons, {sum(1 for n, _ in icons if n in FILLED)} filled variants -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
